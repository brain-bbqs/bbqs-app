-- Data ingestion: unstructured sources in, structured rows out, the graph built from the rows.
--
-- THE GAP. Unstructured material keeps arriving: workshop notes, slide decks, transcripts,
-- emails. The first example is the 2026 workshop's Appendix A, a sensor and device registry. Until
-- now the only routes into the database were the NIH harvesters (structured at the source) and
-- curators typing. Material like Appendix A therefore ended up either nowhere or in a checked-in
-- file the graph read directly. That makes the file a second source of truth (Principle XI), with
-- no audit trail (Principle X), that the people who own the data cannot correct.
--
-- THE SHAPE. Four stages, each a table, so every value can be traced back to the sentence it came
-- from:
--   ingestion_sources  one row per raw document: what it is, where it lives, when it came in.
--   ingestion_records  one row per extracted record. The extractor (a person or an LLM) writes a
--                      payload matching the record kind's JSON Schema (ingest/kinds/*.schema.json).
--                      Each record carries its review flags and status. Curator-only: payloads
--                      quote the source.
--   promote_ingestion_record()  validates a payload and writes it into the domain tables, linking
--                      each domain row back to the record and the source. Re-promoting updates in place.
--   domain tables      the system of record. The KG exporter reads only these.
--
-- THE FIRST RECORD KIND: sensor_deployment. One device as used on one award, which is what Appendix
-- A holds. These rows are what the exporter turns into W3C SOSA/SSN, see kg/sosa/README.md:
--   observable_properties          the vocabulary: what can be observed or actuated (pupil
--                                  diameter, skin conductance, responsive stimulation), aligned
--                                  to device_categories.
--   sensor_deployments             one row per (award, device as named): grant (nullable when
--                                  unresolved), how the award was matched, how the model is known,
--                                  whether a presenter confirmed it aloud.
--   sensor_deployment_devices      deployment -> device_models (the catalogue entry), 0..n.
--   sensor_deployment_properties   deployment -> observable_properties, as 'observes' or 'actuates'.
--   sensor_deployment_presenters   presenter NAMES, curator-only. Anonymous readers and the public
--                                  export see a role ("Postdoc, Suthana lab"), never a student's name,
--                                  and certainly not a guessed one.
--
-- Two invariants of the SOSA shapes are enforced here as CHECKs, so the database refuses what the
-- graph would flag: grant_match 'unresolved' if and only if there is no grant (S-4), and a row no
-- presenter spoke to must say what needs verifying (S-8).
--
-- The vocabulary and the Appendix A records are seeded by 20261006120100, which is generated by
-- ingest/to_sql.py.
--
-- Apply MANUALLY in the KG SQL editor (vpexxhfpvghlejljwpvt), then 20261006120100.

