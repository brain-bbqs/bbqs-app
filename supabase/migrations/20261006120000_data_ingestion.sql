-- ── 7. Promotion ─────────────────────────────────────────────────────────────────────────────
/** Promote one ingestion record into the domain tables, in one transaction. Idempotent: a re-run
 *  updates the deployment in place and replaces its links, so correcting a payload and promoting
 *  again is how a correction lands. Anything the promoter could not resolve is added to the
 *  record's review_flags instead of being guessed. */
CREATE OR REPLACE FUNCTION public.promote_ingestion_record(_record_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  _r     public.ingestion_records;
  _p     jsonb;
  _grant uuid;
  _dep   uuid;
  _dm    uuid;
  _name  text;
  _flags text[] := '{}';
  _claims jsonb := nullif(current_setting('request.jwt.claims', true), '')::jsonb;
BEGIN
  -- Curators and admins, the service role, or the SQL editor (no JWT at all, as for a migration).
  IF NOT (public.is_curator_or_admin(auth.uid())
          OR coalesce(_claims ->> 'role', '') = 'service_role'
          OR _claims IS NULL) THEN
    RAISE EXCEPTION 'Only curators, admins or the service role can promote ingestion records';
  END IF;

  SELECT * INTO _r FROM public.ingestion_records WHERE id = _record_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'No ingestion record %', _record_id;
  END IF;
  IF _r.status = 'rejected' THEN
    RAISE EXCEPTION 'Ingestion record % (%) was rejected at review and cannot be promoted', _r.id, _r.source_locator;
  END IF;
  IF _r.record_kind <> 'sensor_deployment' THEN
    RAISE EXCEPTION 'No promoter for record_kind %', _r.record_kind;
  END IF;
  _p := _r.payload;

  IF nullif(_p ->> 'grant_number', '') IS NOT NULL THEN
    -- grants.grant_number may still carry an application-type prefix (1U01...); payloads never do.
    SELECT id INTO _grant FROM public.grants
     WHERE regexp_replace(grant_number, '^[0-9]', '') = _p ->> 'grant_number'
     ORDER BY grant_number LIMIT 1;
    IF _grant IS NULL THEN
      RAISE EXCEPTION 'Ingestion record % (%): grant % is not in grants. Fix the payload or set grant_match to unresolved',
        _r.id, _r.source_locator, _p ->> 'grant_number';
    END IF;
  END IF;

  INSERT INTO public.sensor_deployments AS d (
    grant_id, award_label, grant_match, grant_note, label_as_named, system_kind, presenter_role,
    presenter_present, verify_note, manufacturer_recorded, manufacturer_hq_recorded, model_recorded,
    model_status, measures_recorded, source_id, source_locator, ingestion_record_id)
  VALUES (
    _grant, _p ->> 'award_label', _p ->> 'grant_match', nullif(_p ->> 'grant_note', ''),
    _p ->> 'label_as_named', _p ->> 'system_kind', nullif(_p ->> 'presenter_role', ''),
    (_p ->> 'presenter_present')::boolean, nullif(_p ->> 'verify_note', ''),
    nullif(_p ->> 'manufacturer_recorded', ''), nullif(_p ->> 'manufacturer_hq_recorded', ''),
    nullif(_p ->> 'model_recorded', ''), _p ->> 'model_status', nullif(_p ->> 'measures_recorded', ''),
    _r.source_id, _r.source_locator, _r.id)
  ON CONFLICT (award_label, label_as_named) DO UPDATE SET
    grant_id = excluded.grant_id, grant_match = excluded.grant_match, grant_note = excluded.grant_note,
    system_kind = excluded.system_kind, presenter_role = excluded.presenter_role,
    presenter_present = excluded.presenter_present, verify_note = excluded.verify_note,
    manufacturer_recorded = excluded.manufacturer_recorded,
    manufacturer_hq_recorded = excluded.manufacturer_hq_recorded,
    model_recorded = excluded.model_recorded, model_status = excluded.model_status,
    measures_recorded = excluded.measures_recorded, source_id = excluded.source_id,
    source_locator = excluded.source_locator, ingestion_record_id = excluded.ingestion_record_id
  RETURNING d.id INTO _dep;

  -- Catalogue links: by model name, then alias. A name the catalogue lacks is flagged, not invented.
  DELETE FROM public.sensor_deployment_devices WHERE deployment_id = _dep;
  FOR _name IN SELECT jsonb_array_elements_text(coalesce(_p -> 'device_models', '[]'::jsonb)) LOOP
    SELECT id INTO _dm FROM public.device_models
     WHERE model_name = _name OR _name = ANY (aliases)
     ORDER BY (model_name = _name) DESC, created_at LIMIT 1;
    IF _dm IS NULL THEN
      _flags := _flags || ('device_not_in_catalogue:' || _name);
    ELSE
      INSERT INTO public.sensor_deployment_devices VALUES (_dep, _dm) ON CONFLICT DO NOTHING;
    END IF;
  END LOOP;

  -- Properties: an unknown key fails the foreign key, and a mis-kinded one fails the kind trigger.
  DELETE FROM public.sensor_deployment_properties WHERE deployment_id = _dep;
  INSERT INTO public.sensor_deployment_properties (deployment_id, property_key, role)
  SELECT _dep, k, 'observes' FROM jsonb_array_elements_text(coalesce(_p -> 'observes', '[]'::jsonb)) k
  UNION
  SELECT _dep, k, 'actuates' FROM jsonb_array_elements_text(coalesce(_p -> 'actuates', '[]'::jsonb)) k;

  UPDATE public.ingestion_records
     SET status = 'promoted', promoted_table = 'sensor_deployments', promoted_id = _dep,
         promoted_at = now(),
         review_flags = coalesce((SELECT array_agg(DISTINCT f ORDER BY f)
                                    FROM unnest(review_flags || _flags) f), '{}')
   WHERE id = _r.id;

  RETURN jsonb_build_object('ok', true, 'record_id', _r.id, 'source_locator', _r.source_locator,
                            'deployment_id', _dep, 'new_flags', to_jsonb(_flags));
END;
$fn$;

/** Promote every record of a source that was not rejected. Returns how many were promoted. */
CREATE OR REPLACE FUNCTION public.promote_ingestion_source(_slug text)
RETURNS int LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $fn$
DECLARE
  _id uuid;
  _n  int := 0;
BEGIN
  FOR _id IN
    SELECT r.id FROM public.ingestion_records r
      JOIN public.ingestion_sources s ON s.id = r.source_id
     WHERE s.slug = _slug AND r.status <> 'rejected'
     ORDER BY r.source_locator
  LOOP
    PERFORM public.promote_ingestion_record(_id);
    _n := _n + 1;
  END LOOP;
  RETURN _n;
END;
$fn$;

REVOKE ALL ON FUNCTION public.promote_ingestion_record(uuid) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.promote_ingestion_source(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.promote_ingestion_record(uuid) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.promote_ingestion_source(text) TO authenticated, service_role;

COMMENT ON FUNCTION public.promote_ingestion_record(uuid) IS
  'Writes one ingestion record into the domain tables for its record_kind (today: sensor_deployment -> sensor_deployments + links), linking the row back to the record and source. Idempotent; re-promote after correcting a payload. Unresolvable catalogue names become review_flags. Curators, admins, service role or SQL editor only.';
