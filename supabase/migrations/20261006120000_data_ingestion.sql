-- Public: what was ingested from where, and the domain rows. Curator-only: payloads and names.
DO $do$
DECLARE
  t text;
  public_read text[] := ARRAY['ingestion_sources', 'observable_properties', 'sensor_deployments',
                              'sensor_deployment_devices', 'sensor_deployment_properties'];
  curator_only text[] := ARRAY['ingestion_records', 'sensor_deployment_presenters'];
BEGIN
  FOREACH t IN ARRAY public_read || curator_only LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
    EXECUTE format('GRANT ALL ON public.%I TO service_role', t);
    EXECUTE format('DROP POLICY IF EXISTS "%1$s writable by curators" ON public.%1$I', t);
    EXECUTE format('CREATE POLICY "%1$s writable by curators" ON public.%1$I FOR ALL TO authenticated '
                   'USING (public.is_curator_or_admin(auth.uid())) '
                   'WITH CHECK (public.is_curator_or_admin(auth.uid()))', t);
    -- Audit floor (Principle X): every write to every one of these tables is attributable.
    EXECUTE format('DROP TRIGGER IF EXISTS trg_audit_%1$s ON public.%1$I', t);
    EXECUTE format('CREATE TRIGGER trg_audit_%1$s AFTER INSERT OR UPDATE OR DELETE ON public.%1$I '
                   'FOR EACH ROW EXECUTE FUNCTION public.log_data_change()', t);
  END LOOP;
  FOREACH t IN ARRAY public_read LOOP
    EXECUTE format('GRANT SELECT ON public.%I TO anon', t);
    EXECUTE format('DROP POLICY IF EXISTS "%1$s readable by all" ON public.%1$I', t);
    EXECUTE format('CREATE POLICY "%1$s readable by all" ON public.%1$I FOR SELECT USING (true)', t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['ingestion_sources', 'ingestion_records', 'observable_properties',
                           'sensor_deployments', 'sensor_deployment_presenters'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated ON public.%1$I', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated BEFORE UPDATE ON public.%1$I '
                   'FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column()', t);
  END LOOP;
END $do$;

