-- ── 1. Sources ───────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.ingestion_sources (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug           text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]*$'),
  kind           text NOT NULL CHECK (kind IN ('workshop_notes', 'slide_deck', 'transcript', 'email',
                                               'form_response', 'registry_table', 'document', 'other')),
  title          text NOT NULL,
  description    text,
  origin_url     text,
  storage_path   text,
  content_sha256 text,
  received_at    timestamptz NOT NULL DEFAULT now(),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.ingestion_sources IS
  'One row per raw document that entered through data ingestion (ingest/README.md). The slug names it in the KG (bid:sosa/source/<slug>). storage_path points at the raw file when it is kept in Storage. Metadata only and readable by anyone; the extracted content is in ingestion_records, which is curator-only.';

-- ── 2. Records ───────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.ingestion_records (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  source_id      uuid NOT NULL REFERENCES public.ingestion_sources(id) ON DELETE CASCADE,
  record_kind    text NOT NULL CHECK (record_kind IN ('sensor_deployment')),
  source_locator text NOT NULL,
  payload        jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  extracted_by   text NOT NULL CHECK (extracted_by ~ '^(human|llm):.+'),
  source_class   text NOT NULL REFERENCES public.source_classes(code),
  status         text NOT NULL DEFAULT 'pending_review'
                   CHECK (status IN ('pending_review', 'accepted', 'rejected', 'promoted')),
  review_flags   text[] NOT NULL DEFAULT '{}',
  review_note    text,
  reviewed_by    text,
  reviewed_at    timestamptz,
  promoted_table text,
  promoted_id    uuid,
  promoted_at    timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, record_kind, source_locator)
);

CREATE INDEX IF NOT EXISTS idx_ingestion_records_status ON public.ingestion_records (record_kind, status);

COMMENT ON TABLE public.ingestion_records IS
  'One structured record extracted from an ingestion source. payload matches ingest/kinds/<record_kind>.schema.json. source_locator is where in the source it came from (a row id, slide or page). extracted_by is human:<what> or llm:<model>, and source_class grades it (curator_fill for a person, llm_extract for a model). review_flags list what a curator should check. promote_ingestion_record() writes it to the domain tables and fills promoted_*.';
COMMENT ON COLUMN public.ingestion_records.status IS
  'pending_review: has review flags or came from a machine. accepted: a curator (or a clean human extraction) cleared it. rejected: never promoted. promoted: written to promoted_table/promoted_id; flags still stand until a curator clears them.';

-- ── 3. Vocabulary ────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.observable_properties (
  key              text PRIMARY KEY CHECK (key ~ '^[a-z][a-z0-9_]*$'),
  property_kind    text NOT NULL DEFAULT 'observable' CHECK (property_kind IN ('observable', 'actuatable')),
  label            text NOT NULL,
  definition       text,
  foi_kind         text CHECK (foi_kind IN ('subject', 'environment')),
  category_key     text REFERENCES public.device_categories(key) ON UPDATE CASCADE ON DELETE SET NULL,
  category_measure text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  CHECK ((property_kind = 'observable') = (foi_kind IS NOT NULL))
);

COMMENT ON TABLE public.observable_properties IS
  'What a sensor can observe (sosa:ObservableProperty) or an actuator act on (sosa:ActuatableProperty). foi_kind says whose property it is: the study subject or their environment. category_key/category_measure align it to a device category and to one of that category''s measures values.';

-- ── 4. Deployments ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.sensor_deployments (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  grant_id                 uuid REFERENCES public.grants(id) ON DELETE SET NULL,
  award_label              text NOT NULL,
  grant_match              text NOT NULL
                             CHECK (grant_match IN ('stated', 'pi_roster', 'institution', 'title', 'ambiguous', 'unresolved')),
  grant_note               text,
  label_as_named           text NOT NULL,
  system_kind              text NOT NULL CHECK (system_kind IN ('sensor', 'platform', 'sensor_actuator')),
  presenter_role           text,
  presenter_present        boolean NOT NULL,
  verify_note              text,
  manufacturer_recorded    text,
  manufacturer_hq_recorded text,
  model_recorded           text,
  model_status             text NOT NULL CHECK (model_status IN ('compiled', 'inferred', 'candidates', 'custom', 'unspecified')),
  measures_recorded        text,
  source_id                uuid REFERENCES public.ingestion_sources(id) ON DELETE SET NULL,
  source_locator           text,
  ingestion_record_id      uuid REFERENCES public.ingestion_records(id) ON DELETE SET NULL,
  confirmed_by             text,
  confirmed_at             timestamptz,
  created_at               timestamptz NOT NULL DEFAULT now(),
  updated_at               timestamptz NOT NULL DEFAULT now(),
  UNIQUE (award_label, label_as_named),
  CONSTRAINT sensor_deployments_unresolved_iff_no_grant CHECK ((grant_match = 'unresolved') = (grant_id IS NULL)),
  CONSTRAINT sensor_deployments_unconfirmed_is_flagged CHECK (presenter_present OR verify_note IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_sensor_deployments_grant ON public.sensor_deployments (grant_id);

COMMENT ON TABLE public.sensor_deployments IS
  'One device as used on one award: a sosa:Sensor or sosa:Platform deployed (ssn:Deployment) on the grant''s study subjects. Filled by promote_ingestion_record(); read by the KG exporter. The *_recorded columns hold what the source said, kept beside the catalogue link so a disagreement stays visible.';
COMMENT ON COLUMN public.sensor_deployments.grant_match IS
  'How award_label was resolved to grant_id: stated in the source; pi_roster (presenter or lab is a named lead); institution (the only BBQS grant there); title; ambiguous (best of several, see grant_note); unresolved (no grant_id).';
COMMENT ON COLUMN public.sensor_deployments.model_status IS
  'How the model is known: compiled (from vendor sources after the fact, not the source document), inferred, candidates (several named), custom (in-house), unspecified.';

CREATE TABLE IF NOT EXISTS public.sensor_deployment_devices (
  deployment_id   uuid NOT NULL REFERENCES public.sensor_deployments(id) ON DELETE CASCADE,
  device_model_id uuid NOT NULL REFERENCES public.device_models(id) ON DELETE CASCADE,
  PRIMARY KEY (deployment_id, device_model_id)
);

CREATE TABLE IF NOT EXISTS public.sensor_deployment_properties (
  deployment_id uuid NOT NULL REFERENCES public.sensor_deployments(id) ON DELETE CASCADE,
  property_key  text NOT NULL REFERENCES public.observable_properties(key) ON UPDATE CASCADE,
  role          text NOT NULL CHECK (role IN ('observes', 'actuates')),
  PRIMARY KEY (deployment_id, property_key, role)
);

-- A sensor observes an observable property and an actuator acts on an actuatable one. Mixing them
-- up would type a stimulation as something measured.
CREATE OR REPLACE FUNCTION public.check_sensor_deployment_property_kind()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $fn$
DECLARE _kind text;
BEGIN
  SELECT property_kind INTO _kind FROM public.observable_properties WHERE key = NEW.property_key;
  IF (NEW.role = 'observes') <> (_kind = 'observable') THEN
    RAISE EXCEPTION 'Property % is %, so it cannot be used as role %', NEW.property_key, _kind, NEW.role;
  END IF;
  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS trg_sensor_deployment_property_kind ON public.sensor_deployment_properties;
CREATE TRIGGER trg_sensor_deployment_property_kind
  BEFORE INSERT OR UPDATE ON public.sensor_deployment_properties
  FOR EACH ROW EXECUTE FUNCTION public.check_sensor_deployment_property_kind();

CREATE TABLE IF NOT EXISTS public.sensor_deployment_presenters (
  deployment_id        uuid PRIMARY KEY REFERENCES public.sensor_deployments(id) ON DELETE CASCADE,
  presenter_name       text NOT NULL,
  name_needs_verifying boolean NOT NULL DEFAULT false,
  investigator_id      uuid REFERENCES public.investigators(id) ON DELETE SET NULL,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.sensor_deployment_presenters IS
  'Who spoke to a deployment, by name. Curator-only, because presenters are often students and some names in the source were guesses (name_needs_verifying). investigator_id is set only once the person is confirmed. Never part of an ingestion payload, so never in the repo or the anon export.';

